#!/usr/bin/env node
/*
 * Builds sdk/dev/board-shell.js from index.html: the board's CSS and markup, wrapped in a script.
 *
 * The widget dev window (sdk/board21-dev.js) runs the REAL board in a frame: it writes a small page with
 * this script in it, which writes index.html's <style> and <body> markup and then loads board.js. So the
 * window, title bar, resize handles, menu and Settings a developer sees are exactly the ones on the
 * smartboard. A script (not a fetch of index.html) so it also works when the files are opened from disk.
 *
 *   node tools/build-sdk.js           rebuild sdk/dev/board-shell.js after changing index.html
 *   node tools/build-sdk.js --check   exit 1 if it's out of date (the tests run this)
 *
 * No dependencies.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'sdk', 'dev', 'board-shell.js');

function build() {
  const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
  const style = html.match(/<style>([\s\S]*?)<\/style>/);
  const body = html.match(/<body>([\s\S]*?)<\/body>/);
  if (!style || !body) throw new Error('index.html: expected one <style> and a <body>');
  // The board page's own scripts are left out: the shell loads board.js itself (no widget registry).
  const markup = body[1].replace(/<script\b[^>]*><\/script>\s*/g, '').trim();
  return `/*
 * GENERATED by tools/build-sdk.js from index.html. Don't edit: run \`node tools/build-sdk.js\`.
 *
 * Used only by the widget dev window (sdk/board21-dev.js): writes the board's CSS and markup, then
 * loads board.js, which sees the #b21-lab block and runs in widget test mode.
 */
(function () {
  var me = document.currentScript;
  var base = me.src.replace(/[?#].*$/, '').replace(/sdk\\/dev\\/board-shell\\.js$/, '');
  var css = ${JSON.stringify(style[1])};
  var markup = ${JSON.stringify(markup)};
  document.write('<style>' + css + '</style></head><body>' + markup + '<script src="' + base + 'board.js"><\\/script>');
})();
`;
}

const out = build();
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== out) { console.error('sdk/dev/board-shell.js is out of date: run `node tools/build-sdk.js`'); process.exit(1); }
  console.log('sdk/dev/board-shell.js is up to date');
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, out);
  console.log('wrote ' + path.relative(ROOT, OUT) + ' (' + Math.round(out.length / 1024) + ' KB)');
}
